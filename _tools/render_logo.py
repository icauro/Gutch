"""Build the Gutch logo variants from the background-free source logo.

Edit only `_docs/assets/gutch_logo.svg`, then run this script to rewrite the
circle and rounded-square variants. Each variant centers the drawing's bounds
on the canvas and scales it so every point stays inside the icon's safe area.
`--check` fails when a variant is stale.
"""

import argparse
import math
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "_docs" / "assets"
SOURCE = ASSETS / "gutch_logo.svg"
BACKGROUND = "#151826"
# The source canvas is a 2004-unit square starting at (40, 20).
X, Y, SIZE = 40, 20, 2004
CENTER = (X + SIZE / 2, Y + SIZE / 2)
# Every point of the drawing stays within this share of the circle radius,
# which leaves a clear margin for app icons and favicons in both variants.
SAFE_RADIUS = 0.82
# The heavy head sits left and only the thin tusk reaches right, so the
# measured center looks left-heavy; this share of the canvas moves it right.
OPTICAL_SHIFT = 0.025
VARIANTS = {
    "gutch_logo_circle.svg":
        f'<circle cx="{X + SIZE // 2}" cy="{Y + SIZE // 2}" r="{SIZE // 2}" fill="{BACKGROUND}"/>',
    # About 11% corner radius: a square with slightly smoothed corners.
    "gutch_logo_square.svg":
        f'<rect x="{X}" y="{Y}" width="{SIZE}" height="{SIZE}" rx="220" fill="{BACKGROUND}"/>',
}


def outline_points(source: str) -> list[tuple[float, float]]:
    """Sample every absolute M/L/C path segment, including curve bulges."""
    points = []
    for path in re.findall(r' d="([^"]+)"', source):
        command, current = None, (0.0, 0.0)
        tokens = re.findall(r"[A-Za-z]|-?\d+(?:\.\d+)?", path)
        index = 0
        while index < len(tokens):
            if tokens[index].isalpha():
                command = tokens[index]
                index += 1
                if command not in "MLCZ":
                    raise ValueError(f"unsupported path command {command!r}; use absolute M, L, C and Z")
                if command == "Z":
                    continue
            if command == "C":
                values = [float(value) for value in tokens[index:index + 6]]
                start, control1, control2, end = current, values[0:2], values[2:4], values[4:6]
                for step in range(1, 33):
                    u = step / 32
                    points.append(tuple(
                        (1 - u) ** 3 * a + 3 * (1 - u) ** 2 * u * b + 3 * (1 - u) * u * u * c + u ** 3 * d
                        for a, b, c, d in zip(start, control1, control2, end)))
                current = (values[4], values[5])
                index += 6
            else:
                current = (float(tokens[index]), float(tokens[index + 1]))
                points.append(current)
                index += 2
                command = "L" if command == "M" else command
    return points


def placement(source: str) -> str:
    """Return the transform that puts the drawing's bounds at the optical center inside the safe circle."""
    points = outline_points(source)
    xs, ys = [x for x, _ in points], [y for _, y in points]
    middle = ((min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2)
    shift, radius = OPTICAL_SHIFT * SIZE, SAFE_RADIUS * SIZE / 2
    # Largest scale that keeps every shifted point inside the safe circle: solve |shift + s * v| = radius.
    scale = min(
        (-shift * vx + math.sqrt((shift * vx) ** 2 + (vx * vx + vy * vy) * (radius ** 2 - shift ** 2)))
        / (vx * vx + vy * vy)
        for vx, vy in ((x - middle[0], y - middle[1]) for x, y in points) if vx or vy)
    return (f"translate({CENTER[0] + shift:.1f} {CENTER[1]:.1f}) scale({scale:.4f}) "
            f"translate({-middle[0]:.1f} {-middle[1]:.1f})")


def render(source: str, background: str) -> str:
    """Put the background first, then the source drawing centered on the canvas."""
    match = re.search(r"(<svg\b[^>]*>\n(?:\s*<title>.*?</title>\n)?)", source)
    end = source.rfind("</svg>")
    if match is None or end < match.end():
        raise ValueError("the source logo must be an <svg> element with an optional leading <title>")
    note = "  <!-- Generated by _tools/render_logo.py from gutch_logo.svg; edit the source instead. -->\n"
    return (match.group(1) + note + f"  {background}\n" + f'  <g transform="{placement(source)}">\n'
            + source[match.end():end] + "  </g>\n" + source[end:])


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a variant differs from the source")
    args = parser.parse_args(argv)
    source = SOURCE.read_text(encoding="utf-8")
    stale = []
    for name, background in VARIANTS.items():
        path = ASSETS / name
        expected = render(source, background)
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                stale.append(name)
        else:
            path.write_text(expected, encoding="utf-8", newline="\n")
            print(f"Wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        print(f"Stale logo variants: {', '.join(stale)}. Run python _tools/render_logo.py.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

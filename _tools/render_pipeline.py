"""Build the README pipeline diagram: how a capture fills the store and an install empties it.

Edit the stages below, then run this script to rewrite
`_docs/assets/pipeline.svg`. `--check` fails when the diagram is stale. The
text uses the banner's embedded Titillium Web subset and colors.
"""

import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from _tools.render_banner import DEEP, INK, MINT, STORE_LOCATIONS, TEAL, font_faces, tags, text, text_width  # noqa: E402


ROOT = Path(__file__).resolve().parents[1]
PIPELINE = ROOT / "_docs" / "assets" / "pipeline.svg"
WIDTH, MARGIN, GAP = 1280, 40, 30
# Each stage: what happens, then how. Defaults come from the capture and install guides.
CAPTURE = (
    ("Your folder", "one version"),
    ("Cut into chunks", "FastCDC, about 128 KiB"),
    ("Name each chunk", "by its BLAKE3 hash"),
    ("Skip known chunks", "each stored once"),
    ("Compress", "Zstandard or LZ4"),
    ("Pack into bundles", "8 MiB each"),
)
INSTALL = (
    ("Plan by bundle", "only what is missing"),
    ("Unpack once", "on all cores"),
    ("Write in place", "to every file using it"),
    ("Check each file", "as soon as it is done"),
    ("Build in staging", "old copy stays in use"),
    ("Swap in", "never half finished"),
)
TITLE_SIZE, DETAIL_SIZE = 18, 15


def caption(x, y, label):
    return text(x, y, 14, "#7d8ba1", label, 600, ' letter-spacing="2.5"')


def stage_row(y, stages, box_width, height):
    """Draw one row of stage boxes joined by arrows."""
    out = []
    for index, (title, detail) in enumerate(stages):
        x = MARGIN + index * (box_width + GAP)
        for content, size, weight in ((title, TITLE_SIZE, 600), (detail, DETAIL_SIZE, 400)):
            if text_width(content, size, weight) > box_width - 16:
                raise ValueError(f"{content!r} does not fit in a {box_width:.0f}-wide stage box")
        middle = x + box_width / 2
        out.append(f'<rect x="{x:.1f}" y="{y}" width="{box_width:.1f}" height="{height}" rx="12" fill="#0f1a2b" '
                   f'stroke="{DEEP}" stroke-width="2"/>')
        out.append(text(f"{middle:.1f}", y + 31, TITLE_SIZE, "#f1f5f9", title, 600, ' text-anchor="middle"'))
        out.append(text(f"{middle:.1f}", y + 54, DETAIL_SIZE, MINT, detail, 400, ' text-anchor="middle"'))
        if index:
            out.append(f'<line x1="{x - GAP + 5:.1f}" y1="{y + height / 2}" x2="{x - 6:.1f}" y2="{y + height / 2}" '
                       f'stroke="{TEAL}" stroke-width="2" marker-end="url(#arrow)"/>')
    return out


def pipeline() -> str:
    box_width = (WIDTH - 2 * MARGIN - (len(CAPTURE) - 1) * GAP) / len(CAPTURE)
    box_height = 74
    capture_y, store_y, install_y = 112, 232, 362
    store_height = 70
    height = install_y + box_height + 74
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{height}" viewBox="0 0 {WIDTH} {height}">',
        "<title>Gutch pipeline: capture fills the store, install rebuilds a folder from it</title>",
        "<!-- Generated by _tools/render_pipeline.py; edit that script instead. -->",
        f"""<defs>
  <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
    <stop offset="0" stop-color="#0b0e18"/><stop offset="1" stop-color="{INK}"/>
  </linearGradient>
  <marker id="arrow" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="7" markerHeight="7" orient="auto">
    <path d="M0 0 L10 5 L0 10 z" fill="{TEAL}"/>
  </marker>
</defs>""",
        f'<rect width="{WIDTH}" height="{height}" rx="24" fill="url(#bg)"/>',
        text(MARGIN, 58, 30, "#f1f5f9", "From a folder to the store and back", 700),
        caption(MARGIN, capture_y - 14, "CAPTURE"),
        *stage_row(capture_y, CAPTURE, box_width, box_height),
        caption(MARGIN, install_y - 14, "INSTALL"),
        *stage_row(install_y, INSTALL, box_width, box_height),
    ]

    # The store sits between the rows: capture flows down into it on the right, install out of it on the left.
    out.append(f'<rect x="{MARGIN}" y="{store_y}" width="{WIDTH - 2 * MARGIN}" height="{store_height}" rx="14" '
               f'fill="#12263a" stroke="{TEAL}" stroke-width="2"/>')
    label_y = store_y + store_height / 2 + 6
    out.append(text(MARGIN + 24, label_y, 18, MINT, "STORE", 700, ' letter-spacing="2.5"'))
    detail = "bundles of chunks, plus a small record for each snapshot; optionally encrypted with AES-256-GCM"
    out.append(text(MARGIN + 24 + text_width("STORE", 18, 700) + 2.5 * 5 + 20, label_y, 16, "#cbd5e1", detail))
    chips, chips_end = tags(0, 0, STORE_LOCATIONS, 14)
    out.append(tags(WIDTH - MARGIN - 20 - chips_end, store_y + (store_height - 26) / 2, STORE_LOCATIONS, 14)[0])
    last_capture = MARGIN + (len(CAPTURE) - 1) * (box_width + GAP) + box_width / 2
    # Off center, so the arrow clears the INSTALL caption.
    first_install = MARGIN + box_width * 0.75
    for x, top, bottom in ((last_capture, capture_y + box_height, store_y),
                           (first_install, store_y + store_height, install_y)):
        out.append(f'<line x1="{x:.1f}" y1="{top + 4}" x2="{x:.1f}" y2="{bottom - 5}" stroke="{TEAL}" stroke-width="2" '
                   f'marker-end="url(#arrow)"/>')

    note = ("Downloads overlap with unpacking, and a repair runs the same steps for the broken files only.")
    out.append(text(MARGIN, install_y + box_height + 42, 16, "#a3b0c2", note))
    out.append("</svg>")
    body = "\n".join(out) + "\n"
    return body.replace("<defs>\n", "<defs>\n" + font_faces(body), 1)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the diagram differs from this script")
    args = parser.parse_args(argv)
    expected = pipeline()
    if args.check:
        if not PIPELINE.exists() or PIPELINE.read_text(encoding="utf-8") != expected:
            print("Stale pipeline diagram. Run python _tools/render_pipeline.py.", file=sys.stderr)
            return 1
        return 0
    PIPELINE.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Wrote {PIPELINE.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

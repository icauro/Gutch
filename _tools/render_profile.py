"""Build the README install profile from a Perfetto screenshot.

`_docs/assets/install_profile.webp` is a crop of Perfetto's timeline for one
`installation reconstruct --profile detailed` run: the main thread, every
reconstruction worker and the output threads. This script frames it with a
title, a legend and the test conditions, and embeds it in
`_docs/assets/install_profile.svg` so the README needs one file. Edit this
script or replace the screenshot, then run it; `--check` fails when the SVG
is stale. When the screenshot changes, update `RUN` to match its trace.
"""

import argparse
import base64
from pathlib import Path
import struct
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from _tools.render_banner import DEEP, INK, MINT, TEAL, font_faces, text, text_width  # noqa: E402


ROOT = Path(__file__).resolve().parents[1]
SCREENSHOT = ROOT / "_docs" / "assets" / "install_profile.webp"
PROFILE = ROOT / "_docs" / "assets" / "install_profile.svg"
WIDTH, MARGIN = 1280, 40
# What the screenshot shows, taken from its trace and the machine it ran on.
RUN = {
    "dataset": "Blender 5.1.0 for Windows: 977 MB in 6,368 files, rebuilt from a 380 MB store",
    "seconds": "0.65 s",
    "workers": 12,
    "machine": ("AMD Ryzen 9 7900, 12 cores", "KIOXIA Exceria G2 NVMe SSD", "Windows 11",
                "default settings", "store already in memory"),
}
# Perfetto's colors for the three kinds of slices, so the legend matches the picture.
LEGEND = (
    ("#d9653b", "one bundle job"),
    ("#e1a3f0", "read, unpack, check and write its chunks"),
    ("#3b7fb3", "finish files and move them into place"),
)


def webp_size(data: bytes) -> tuple[int, int]:
    """Read the canvas size from a WebP header (extended, lossy or lossless)."""
    if data[:4] != b"RIFF" or data[8:12] != b"WEBP":
        raise ValueError("the screenshot must be a WebP image")
    kind = data[12:16]
    if kind == b"VP8X":
        return int.from_bytes(data[24:27], "little") + 1, int.from_bytes(data[27:30], "little") + 1
    if kind == b"VP8 ":
        width, height = struct.unpack("<HH", data[26:30])
        return width & 0x3FFF, height & 0x3FFF
    if kind == b"VP8L":
        bits = int.from_bytes(data[21:25], "little")
        return (bits & 0x3FFF) + 1, ((bits >> 14) & 0x3FFF) + 1
    raise ValueError(f"unsupported WebP chunk {kind!r}")


def profile(screenshot: bytes) -> str:
    pixel_width, pixel_height = webp_size(screenshot)
    shot_width = WIDTH - 2 * MARGIN
    shot_height = round(shot_width * pixel_height / pixel_width)
    shot_y = 128
    legend_y = shot_y + shot_height + 42
    height = legend_y + 66
    encoded = base64.b64encode(screenshot).decode("ascii")
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="{WIDTH}" '
        f'height="{height}" viewBox="0 0 {WIDTH} {height}">',
        "<title>Gutch install profile: every worker busy until the install is done</title>",
        "<!-- Generated by _tools/render_profile.py from install_profile.webp; edit those instead. -->",
        f"""<defs>
  <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
    <stop offset="0" stop-color="#0b0e18"/><stop offset="1" stop-color="{INK}"/>
  </linearGradient>
  <clipPath id="shot"><rect x="{MARGIN}" y="{shot_y}" width="{shot_width}" height="{shot_height}" rx="10"/></clipPath>
</defs>""",
        f'<rect width="{WIDTH}" height="{height}" rx="24" fill="url(#bg)"/>',
        text(MARGIN, 64, 32, "#f1f5f9", f"{RUN['workers']} workers busy until the install is done", 700),
        text(MARGIN, 100, 18, "#cbd5e1", f"{RUN['dataset']} in ", 400)
        + text(MARGIN + text_width(f"{RUN['dataset']} in ", 18, 400), 100, 18, MINT, RUN["seconds"], 600),
        f'<image x="{MARGIN}" y="{shot_y}" width="{shot_width}" height="{shot_height}" clip-path="url(#shot)" '
        f'preserveAspectRatio="none" href="data:image/webp;base64,{encoded}"/>',
        f'<rect x="{MARGIN}" y="{shot_y}" width="{shot_width}" height="{shot_height}" rx="10" fill="none" '
        f'stroke="{DEEP}" stroke-width="2"/>',
    ]
    x = MARGIN
    for color, label in LEGEND:
        out.append(f'<rect x="{x}" y="{legend_y - 13}" width="14" height="14" rx="3" fill="{color}"/>'
                   + text(x + 22, legend_y, 17, "#cbd5e1", label))
        x += 22 + text_width(label, 17, 400) + 34
    conditions = " · ".join(RUN["machine"])
    out.append(text(MARGIN, legend_y + 34, 15, "#7d8ba1", conditions))
    credit = "Profiled with --profile detailed, shown in Perfetto"
    out.append(text(f"{WIDTH - MARGIN - text_width(credit, 15, 400):.1f}", legend_y + 34, 15, TEAL, credit))
    out.append("</svg>")
    body = "\n".join(out) + "\n"
    return body.replace("<defs>\n", "<defs>\n" + font_faces(body), 1)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the profile differs from its sources")
    args = parser.parse_args(argv)
    expected = profile(SCREENSHOT.read_bytes())
    if args.check:
        if not PROFILE.exists() or PROFILE.read_text(encoding="utf-8") != expected:
            print("Stale install profile. Run python _tools/render_profile.py.", file=sys.stderr)
            return 1
        return 0
    PROFILE.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Wrote {PROFILE.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
